/**
 * Al-Amira ERP V2 — Client-Side Cache & In-Flight Request Deduplicator
 * 
 * Architecture:
 * 1. In-flight Promise deduplication: merges concurrent identical requests into a single promise.
 * 2. In-memory TTL cache: caches reference and list queries with role and user isolation.
 * 3. Mutation invalidation: selectively purges cached keys when data is created, updated, or deleted.
 * 4. Auth isolation: completely clears all cached data upon user logout or identity switch.
 * 5. Stale-Write Protection via Epoch Counters: prevents late-resolving in-flight requests started
 *    before logout or mutation from repopulating the cache with stale data.
 * 6. Zero external dependencies: pure TypeScript Map implementation without insecure local persistence.
 */

interface CacheEntry<T> {
  data: T
  expiresAt: number
}

class CacheService {
  private cache = new Map<string, CacheEntry<unknown>>()
  private inFlight = new Map<string, Promise<unknown>>()
  private globalEpoch = 0
  private namespaceEpochs = new Map<string, number>()

  private getNamespace(key: string): string {
    return key.split('::')[0] || ''
  }

  private getNamespaceEpoch(namespace: string): number {
    return this.namespaceEpochs.get(namespace) || 0
  }

  /**
   * Generates a unique, role-isolated cache key.
   */
  public createKey(namespace: string, params?: unknown, role?: string, userId?: string): string {
    const serializedParams = params !== undefined ? JSON.stringify(params) : ''
    const roleKey = role || 'ANON'
    const userKey = userId || 'GUEST'
    return `${namespace}::${roleKey}::${userKey}::${serializedParams}`
  }

  /**
   * Executes or deduplicates an asynchronous operation, caching successful results.
   * 
   * @param key Unique cache key generated by createKey
   * @param fetcher Async function retrieving data from Supabase
   * @param ttlMs Time-to-live in milliseconds (default: 60,000ms = 1 min)
   * @param forceFresh When true, bypasses existing cached data but still deduplicates concurrent calls
   */
  public async getOrFetch<T>(
    key: string,
    fetcher: () => Promise<T>,
    ttlMs: number = 60_000,
    forceFresh: boolean = false
  ): Promise<T> {
    const now = Date.now()

    // 1. Check existing unexpired cache entry if not forcing fresh data
    if (!forceFresh) {
      const entry = this.cache.get(key)
      if (entry && entry.expiresAt > now) {
        return entry.data as T
      }
    }

    // 2. Check for an in-flight duplicate promise to coalesce concurrent requests
    const pendingPromise = this.inFlight.get(key)
    if (pendingPromise) {
      return pendingPromise as Promise<T>
    }

    // 3. Capture current epoch state for write-staleness prevention
    const requestGlobalEpoch = this.globalEpoch
    const ns = this.getNamespace(key)
    const requestNsEpoch = this.getNamespaceEpoch(ns)

    // 4. Initiate request and track in-flight promise
    const promise = fetcher()
      .then((data) => {
        // Enforce epoch guard: drop write if global clear() or namespace invalidation happened while in-flight
        if (
          this.globalEpoch === requestGlobalEpoch &&
          this.getNamespaceEpoch(ns) === requestNsEpoch &&
          ttlMs > 0
        ) {
          this.cache.set(key, {
            data,
            expiresAt: Date.now() + ttlMs,
          })
        }
        return data
      })
      .finally(() => {
        if (this.inFlight.get(key) === promise) {
          this.inFlight.delete(key)
        }
      })

    this.inFlight.set(key, promise)
    return promise
  }

  /**
   * Retrieves a cached value directly if present and unexpired.
   */
  public get<T>(key: string): T | null {
    const entry = this.cache.get(key)
    if (entry && entry.expiresAt > Date.now()) {
      return entry.data as T
    }
    return null
  }

  /**
   * Manually sets a cache value with a custom TTL.
   */
  public set<T>(key: string, data: T, ttlMs: number = 60_000): void {
    if (ttlMs > 0) {
      this.cache.set(key, {
        data,
        expiresAt: Date.now() + ttlMs,
      })
    }
  }

  /**
   * Invalidates all cache entries matching a namespace prefix.
   * e.g., invalidateNamespace('products') clears all product queries across all parameters.
   */
  public invalidateNamespace(namespace: string): void {
    const currentEpoch = this.getNamespaceEpoch(namespace)
    this.namespaceEpochs.set(namespace, currentEpoch + 1)

    const prefix = `${namespace}::`
    for (const key of this.cache.keys()) {
      if (key.startsWith(prefix)) {
        this.cache.delete(key)
      }
    }
    for (const key of this.inFlight.keys()) {
      if (key.startsWith(prefix)) {
        this.inFlight.delete(key)
      }
    }
  }

  /**
   * Wipes the entire cache and all in-flight tracking.
   * Increments the global epoch counter so any in-flight promises started
   * before this call can NEVER write stale data to the cache upon resolving.
   */
  public clear(): void {
    this.globalEpoch++
    this.namespaceEpochs.clear()
    this.cache.clear()
    this.inFlight.clear()
  }

  /**
   * Returns current cache statistics for monitoring and testing.
   */
  public getStats(): { cachedEntries: number; inFlightRequests: number } {
    return {
      cachedEntries: this.cache.size,
      inFlightRequests: this.inFlight.size,
    }
  }
}

export const cacheService = new CacheService()
